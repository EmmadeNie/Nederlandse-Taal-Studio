// Collects the recorded scenes (raw/<lang>/<scene>/manifest.json) into one module
// for the Remotion edit, and notes whether there is music (raw/music.mp3).
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from "node:fs";
import path from "node:path";
import { RAW_DIR, DEMO_DIR } from "./config.mjs";

const out = {};
for (const lang of existsSync(RAW_DIR) ? readdirSync(RAW_DIR) : []) {
  const dir = path.join(RAW_DIR, lang);
  if (!statSync(dir).isDirectory()) continue;
  for (const scene of readdirSync(dir)) {
    const file = path.join(dir, scene, "manifest.json");
    if (!existsSync(file)) continue;
    const m = JSON.parse(readFileSync(file, "utf8"));
    (out[lang] ??= {})[scene] = { duration: m.duration, frames: m.frames, marks: m.marks };
  }
}
const music = existsSync(path.join(RAW_DIR, "music.mp3"));
writeFileSync(
  path.join(DEMO_DIR, "remotion", "manifests.js"),
  `// Generated by prepare.mjs. Do not edit.\nexport const MUSIC = ${music};\nexport const MANIFESTS = ${JSON.stringify(out)};\n`,
);
for (const [lang, scenes] of Object.entries(out)) console.log(lang, Object.keys(scenes).join(", "));
console.log("music:", music);
